"""Documented printer + reader + software configurations, not brand-wide promises.

The legacy ``firmwares`` key remains compatible with saved settings and older
clients. Each entry now describes a complete reading configuration and its effect.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path
from urllib.error import HTTPError

EXPORT_FORMATS = ("openspool", "opentag3d")

GROUP_ORDER = ("native", "external", "incompatible", "none")
_LEGACY_IDS = {"u1_stock": ("u1", "stock"),
               "bambu_openspool": ("bambu", "openspool_network"),
               "prusa": ("prusa_generic", "stock")}
CONNECTIONS = ('integrated','usb','network','can','none','custom')
FIRMWARE_KINDS = ('stock','modified','integration')
EFFECTS = ('printer','inventory','standalone','none')
DEFAULT = "u1"
PRINTERS_URL = "https://raw.githubusercontent.com/ArN-LaB/Spoolscribe-/main/data/printers.json"


def _resource_dir() -> str:
    import sys
    if getattr(sys, "frozen", False):
        return getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(sys.executable)))
    return str(Path(__file__).resolve().parents[2])


def bundled_path() -> Path:
    return Path(os.environ.get("SPOOLSCRIBE_RESOURCE_DIR") or _resource_dir()) / "data" / "printers.json"


def user_path() -> Path | None:
    home = os.environ.get("SPOOLSCRIBE_DATA_HOME")
    return Path(home) / "data" / "printers.json" if home else None


MAX_CATALOGUE_BYTES = 512 * 1024
EVIDENCE = ('documented', 'experimental', 'unverified')
# Shared contract (docs/PRINTER-CATALOGUE-CONTRACT.md). Companion applies the
# same rules, in the same order, with the same error codes, on the shared
# conformance corpus generated by scripts/export_printer_catalogue.py.
_ID = re.compile(r'[a-z0-9][a-z0-9_.-]{0,63}')
_TOKEN = re.compile(r'[a-z0-9][a-z0-9_.-]{0,47}')
_DATE = re.compile(r'([0-9]{4})-([0-9]{2})-([0-9]{2})')
_DATETIME = re.compile(r'([0-9]{4})-([0-9]{2})-([0-9]{2})T([0-9]{2}):([0-9]{2})(?::([0-9]{2})(?:\.([0-9]{1,6}))?)?'
                       r'(Z|[+-][0-9]{2}:[0-9]{2})')
MAX_DEPTH = 64
_LIMITS = dict(printers=500, firmwares=64, reader_formats=32, fields=50, groups=16, external_readers=100,
               unverified=100, id=64, label=200, vendor=100, choice_label=120, text=2000, url=500)


class CatalogueError(ValueError):
    """Invalid or inadmissible catalogue; ``code`` is stable and shared with Companion."""

    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


def _text_ok(value, limit: int, *, empty: bool = False) -> bool:
    """Bounded string in code points, without NUL/C0 controls (tab and newline allowed) or lone surrogates."""
    if not isinstance(value, str) or len(value) > limit or (not empty and not value):
        return False
    return not any((ord(c) < 0x20 and c not in '\t\n') or 0xD800 <= ord(c) <= 0xDFFF for c in value)


def _https(value) -> bool:
    return _text_ok(value, _LIMITS['url']) and value.startswith('https://') and len(value) > len('https://')


def parse_instant(value):
    """Calendar-checked ISO date (midnight UTC) or date-time with an explicit offset; None if invalid."""
    from datetime import datetime, timedelta, timezone
    if not isinstance(value, str):
        return None
    m = _DATETIME.fullmatch(value)
    d = None if m else _DATE.fullmatch(value)
    try:
        if d:
            return datetime(int(d[1]), int(d[2]), int(d[3]), tzinfo=timezone.utc)
        if not m:
            return None
        if m[8] == 'Z':
            tz = timezone.utc
        else:
            hours, minutes = int(m[8][1:3]), int(m[8][4:6])
            if hours > 23 or minutes > 59:
                return None
            sign = 1 if m[8][0] == '+' else -1
            tz = timezone(sign * timedelta(hours=hours, minutes=minutes))
        micros = int((m[7] or '').ljust(6, '0') or 0)
        return datetime(int(m[1]), int(m[2]), int(m[3]), int(m[4]), int(m[5]), int(m[6] or 0), micros,
                        tzinfo=tz).astimezone(timezone.utc)
    except (ValueError, OverflowError):
        return None


def _fail(code: str, message: str):
    raise CatalogueError(code, message)


def validate_catalogue(doc) -> dict:
    """Structural, backward-compatible reading of a v1 document; returns it unchanged.

    Absent optional metadata stays unknown. Extra optional fields are tolerated
    and never interpreted. Checks run in a fixed order (first failure wins).
    """
    if not isinstance(doc, dict) or doc.get('format') != 'spoolscribe-printers':
        _fail('format', "Liste d'imprimantes : format inconnu.")
    if type(doc.get('version')) is not int or doc['version'] != 1:
        _fail('version', "Liste d'imprimantes : version inconnue.")
    if 'configuration_schema' in doc and (type(doc['configuration_schema']) is not int or doc['configuration_schema'] != 1):
        _fail('schema', 'Schéma de configuration inconnu.')
    if 'updated' in doc and parse_instant(doc['updated']) is None:
        _fail('updated', 'Date de la liste invalide.')
    if 'source' in doc and not _https(doc['source']):
        _fail('source', 'Source de la liste invalide.')
    groups = doc.get('groups')
    if 'groups' in doc and (not isinstance(groups, dict) or len(groups) > _LIMITS['groups'] or any(
            k not in GROUP_ORDER or not _text_ok(v, _LIMITS['text']) for k, v in groups.items())):
        _fail('groups', 'Groupes invalides.')
    printers = doc.get('printers')
    if not isinstance(printers, list) or not printers or len(printers) > _LIMITS['printers']:
        _fail('printers', "Liste d'imprimantes vide ou invalide.")
    schema = doc.get('configuration_schema') == 1
    seen = set()
    for printer in printers:
        if not isinstance(printer, dict):
            _fail('printer', 'Imprimante invalide.')
        pid = printer.get('id')
        if not isinstance(pid, str) or not _ID.fullmatch(pid):
            _fail('id', 'Identifiant d’imprimante invalide.')
        if pid in seen:
            _fail('duplicate', f'Imprimante {pid} dupliquée.')
        seen.add(pid)
        if 'hidden' in printer and type(printer['hidden']) is not bool:
            _fail('hidden', 'Profil historique invalide.')
        if printer.get('group') not in GROUP_ORDER:
            _fail('group', f'Imprimante {pid} : groupe invalide.')
        if not _text_ok(printer.get('label'), _LIMITS['label']) or any(
                key in printer and not _text_ok(printer[key], limit, empty=True)
                for key, limit in (('vendor', _LIMITS['vendor']), ('reader', _LIMITS['text']), ('help', _LIMITS['text']))):
            _fail('text', f"Texte d'imprimante {pid} invalide.")
        fields = printer.get('fields')
        if 'fields' in printer and (not isinstance(fields, dict) or len(fields) > _LIMITS['fields'] or any(
                not _text_ok(k, _LIMITS['label']) or not _text_ok(v, _LIMITS['text'], empty=True) for k, v in fields.items())):
            _fail('fields', f'Imprimante {pid} : champs invalides.')
        firmwares = printer.get('firmwares')
        if not isinstance(firmwares, list) or not firmwares or len(firmwares) > _LIMITS['firmwares']:
            _fail('firmwares', f'Imprimante {pid} : firmwares invalides.')
        required = schema and not printer.get('hidden')
        ids = set()
        for fw in firmwares:
            _validate_configuration(pid, fw, ids, required)
    readers = doc.get('external_readers')
    if 'external_readers' in doc and (not isinstance(readers, list) or len(readers) > _LIMITS['external_readers'] or any(
            not isinstance(r, dict) or not isinstance(r.get('id'), str) or not _ID.fullmatch(r['id'])
            or not _text_ok(r.get('label'), _LIMITS['label']) or ('url' in r and not _https(r['url']))
            or any(k in r and not _text_ok(r[k], _LIMITS['text'], empty=True) for k in ('works_with', 'tags'))
            for r in readers)):
        _fail('external_readers', 'Lecteurs externes invalides.')
    notes = doc.get('unverified')
    if 'unverified' in doc and (not isinstance(notes, list) or len(notes) > _LIMITS['unverified'] or any(
            not _text_ok(n, _LIMITS['text']) for n in notes)):
        _fail('unverified', 'Mentions non vérifiées invalides.')
    return doc


def _validate_configuration(pid: str, fw, ids: set, required: bool) -> None:
    if not isinstance(fw, dict):
        _fail('firmwares', f'Imprimante {pid} : firmwares invalides.')
    fid = fw.get('id')
    if not isinstance(fid, str) or not _ID.fullmatch(fid):
        _fail('id', f'Imprimante {pid} : identifiant de configuration invalide.')
    if fid in ids:
        _fail('duplicate', f'Imprimante {pid} : configuration {fid} dupliquée.')
    ids.add(fid)
    if type(fw.get('openspool')) is not bool:
        _fail('firmwares', f'Imprimante {pid} : firmwares invalides.')
    if not _text_ok(fw.get('label'), _LIMITS['label']) or (
            'choice_label' in fw and not _text_ok(fw['choice_label'], _LIMITS['choice_label'])) or any(
            key in fw and not _text_ok(fw[key], _LIMITS['text'], empty=True) for key in ('reader', 'notes')):
        _fail('text', 'Libellé ou texte de configuration invalide.')
    if 'url' in fw and not _https(fw['url']):
        _fail('url', 'Source de configuration invalide.')
    supported = fw.get('formats', ['openspool'] if fw['openspool'] else [])
    if (not isinstance(supported, list) or any(x not in EXPORT_FORMATS for x in supported)
            or len(set(supported)) != len(supported) or ('openspool' in supported) != fw['openspool']):
        _fail('formats', 'Formats de lecteur invalides.')
    read = fw.get('reader_formats')
    if 'reader_formats' in fw and (not isinstance(read, list) or len(read) > _LIMITS['reader_formats']
                                   or any(not isinstance(x, str) or not _TOKEN.fullmatch(x) for x in read)
                                   or len(set(read)) != len(read) or not set(supported).issubset(read)):
        _fail('reader_formats', 'Formats du lecteur invalides.')
    for key, allowed in (('connection', CONNECTIONS), ('firmware_kind', FIRMWARE_KINDS), ('effect', EFFECTS),
                         ('evidence', EVIDENCE)):
        if key in fw and fw[key] not in allowed:
            _fail('metadata', f'Configuration {fid} : {key} inconnu.')
    if 'checked' in fw and (not isinstance(fw['checked'], str) or parse_instant(fw['checked']) is None):
        _fail('date', f'Configuration {fid} : date documentaire invalide.')
    if (required or 'connection' in fw) and any(
            key not in fw for key in ('connection', 'firmware_kind', 'effect', 'evidence', 'reader_formats',
                                      'reader', 'notes', 'url', 'checked')):
        _fail('metadata', 'Configuration de lecture invalide ou non documentée.')
    # An export needs a documented or experimental configuration with an effect;
    # historical entries without any of this metadata keep their old meaning.
    if supported and (required or 'evidence' in fw or 'effect' in fw) and (
            fw.get('evidence') not in ('documented', 'experimental') or fw.get('effect') == 'none'):
        _fail('export', 'Export non autorisé par une configuration non vérifiée.')


def update_refusal(doc: dict) -> str | None:
    """A structurally valid document is admissible as an update only with a valid date and source."""
    if parse_instant(doc.get('updated')) is None:
        return 'updated_missing'
    if not _https(doc.get('source')):
        return 'source_missing'
    return None


def semantic_bytes(doc: dict) -> bytes:
    """Canonical data, without formatting, the runtime ``_origin``/``_update`` markers or the
    notation of ``updated`` (compared by time value in :func:`compare_update`)."""
    data = {k: v for k, v in doc.items() if k not in ('_origin', '_update', 'updated')}
    return json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')


def compare_update(active: dict | None, candidate: dict) -> str:
    """``install``, ``unchanged``, ``conflict``, ``regression`` or ``not_admissible``; compares by time value."""
    if update_refusal(candidate):
        return 'not_admissible'
    current = parse_instant(active.get('updated')) if active else None
    incoming = parse_instant(candidate['updated'])
    if current is None or incoming > current:
        return 'install'
    if incoming < current:
        return 'regression'
    return 'unchanged' if semantic_bytes(active) == semantic_bytes(candidate) else 'conflict'


def parse_catalogue_bytes(raw: bytes) -> dict:
    """Strict reading of bytes: bound, UTF-8 without BOM, JSON without duplicate keys or non-finite numbers."""
    if not isinstance(raw, (bytes, bytearray)) or len(raw) > MAX_CATALOGUE_BYTES:
        _fail('size', 'Liste d’imprimantes trop volumineuse.')
    if bytes(raw[:3]) == b'\xef\xbb\xbf':
        _fail('utf8', 'Liste d’imprimantes : marque d’ordre des octets refusée.')
    try:
        text = bytes(raw).decode('utf-8')
    except UnicodeDecodeError:
        _fail('utf8', 'Liste d’imprimantes : UTF-8 invalide.')
    from scripts import db_io
    try:
        doc = db_io.parse_json(text)
    except (db_io.DatabaseError, RecursionError):
        _fail('json', 'Liste d’imprimantes : JSON invalide.')
    if _depth(doc) > MAX_DEPTH:
        _fail('json', 'Liste d’imprimantes : imbrication excessive.')
    return validate_catalogue(doc)


def _depth(value) -> int:
    """Nesting depth of arrays/objects (a scalar is 0), computed without recursion."""
    deepest, stack = 0, [(value, 1)]
    while stack:
        item, level = stack.pop()
        children = item.values() if isinstance(item, dict) else item if isinstance(item, list) else None
        if children is None:
            continue
        deepest = max(deepest, level)
        stack.extend((child, level + 1) for child in children)
    return deepest


def projection(doc: dict) -> dict:
    """Normalised view shared with Companion: absent fields are None (unknown), never defaults."""
    instant = parse_instant(doc.get('updated'))
    epoch = None
    if instant is not None:
        from datetime import datetime, timezone
        delta = instant - datetime(1970, 1, 1, tzinfo=timezone.utc)
        epoch = (delta.days * 86400 + delta.seconds) * 1000000 + delta.microseconds
    get = lambda d, k: d.get(k)
    return {
        'format': doc['format'], 'version': doc['version'], 'configurationSchema': doc.get('configuration_schema'),
        'updated': get(doc, 'updated'), 'updatedEpochMicros': epoch, 'source': get(doc, 'source'),
        'updateRefusal': update_refusal(doc), 'groups': doc.get('groups'),
        'printers': [{
            'id': p['id'], 'vendor': get(p, 'vendor'), 'label': p['label'], 'group': p['group'],
            'hidden': p.get('hidden') is True, 'reader': get(p, 'reader'), 'help': get(p, 'help'),
            'fields': p.get('fields'),
            'configurations': [{
                'id': f['id'], 'label': f['label'], 'choiceLabel': get(f, 'choice_label'), 'openspool': f['openspool'],
                'formats': list(f.get('formats', ['openspool'] if f['openspool'] else [])),
                'readerFormats': get(f, 'reader_formats'), 'connection': get(f, 'connection'),
                'firmwareKind': get(f, 'firmware_kind'), 'reader': get(f, 'reader'), 'effect': get(f, 'effect'),
                'evidence': get(f, 'evidence'), 'notes': get(f, 'notes'), 'url': get(f, 'url'),
                'checked': get(f, 'checked'),
            } for f in p['firmwares']],
        } for p in doc['printers']],
        'externalReaders': [{'id': r['id'], 'label': r['label'], 'url': get(r, 'url'), 'worksWith': get(r, 'works_with'),
                             'tags': get(r, 'tags')} for r in doc.get('external_readers', [])]
        if 'external_readers' in doc else None,
        'unverified': doc.get('unverified'),
    }


def _read_bounded(path: Path) -> bytes:
    with open(path, 'rb') as stream:
        raw = stream.read(MAX_CATALOGUE_BYTES + 1)
    return raw


def load_catalogue() -> dict:
    """User copy when valid and at least as recent (by time value), otherwise the bundled list.

    A bad, unreadable or undated user file never fails and never replaces the bundled list.
    """
    bundled = parse_catalogue_bytes(_read_bounded(bundled_path()))
    user = user_path()
    if user and user.is_file():
        try:
            candidate = parse_catalogue_bytes(_read_bounded(user))
            mine, base = parse_instant(candidate.get('updated')), parse_instant(bundled.get('updated'))
            if mine is not None and (base is None or mine >= base):
                candidate["_origin"] = "user"
                return candidate
        except (OSError, ValueError):
            pass
    bundled["_origin"] = "bundled"
    return bundled


def _profiles(catalogue: dict | None = None) -> dict:
    out = {}
    for printer in (catalogue if catalogue is not None else load_catalogue())["printers"]:
        firmwares = printer["firmwares"]
        out[printer["id"]] = {
            "label": printer["label"], "vendor": printer.get("vendor", ""), "group": printer["group"],
            "reader": printer.get("reader", ""), "help": printer.get("help", ""),
            "fields": printer.get("fields", {}), "firmwares": firmwares,
            "hidden": printer.get('hidden') is True,
            # The printer can export when a firmware reads at least one supported format.
            "nfc": any(f.get("formats",["openspool"] if f["openspool"] else []) for f in firmwares),
        }
    return out


PROFILES = _profiles()


def reload() -> dict:
    PROFILES.clear()
    PROFILES.update(_profiles())
    return PROFILES


def resolve(printer_id: str | None, firmware_id: str | None = None) -> tuple[str, str]:
    """Valid (printer, firmware) pair for stored settings, with legacy identifiers mapped."""
    printer_id, legacy_firmware = _LEGACY_IDS.get(printer_id or "", (printer_id, None))
    if printer_id not in PROFILES:
        printer_id = DEFAULT if DEFAULT in PROFILES else next(iter(PROFILES))
    firmwares = PROFILES[printer_id]["firmwares"]
    wanted = legacy_firmware or firmware_id
    firmware = next((f["id"] for f in firmwares if f["id"] == wanted), firmwares[0]["id"])
    return printer_id, firmware


def firmware(printer_id: str, firmware_id: str | None) -> dict:
    printer_id, firmware_id = resolve(printer_id, firmware_id)
    return next(f for f in PROFILES[printer_id]["firmwares"] if f["id"] == firmware_id)


def formats(printer_id: str, firmware_id: str | None = None) -> tuple[str, ...]:
    printer_id,legacy=_LEGACY_IDS.get(printer_id,(printer_id,None))
    firmware_id=legacy or firmware_id
    if printer_id not in PROFILES or firmware_id is not None and firmware_id not in [f['id'] for f in PROFILES[printer_id]['firmwares']]:
        return ()
    fw=firmware(printer_id,firmware_id)
    return tuple(fw.get('formats',['openspool'] if fw['openspool'] else []))


def configuration(printer_id: str, firmware_id: str | None = None) -> dict:
    """Description for presentation; old catalogues keep their historical API."""
    printer_id,firmware_id=resolve(printer_id,firmware_id)
    fw=dict(firmware(printer_id,firmware_id))
    profile=PROFILES[printer_id]
    fw.setdefault('connection','integrated' if profile['group'] in ('native','incompatible') else 'none' if profile['group']=='none' else 'custom')
    fw.setdefault('firmware_kind','integration')
    fw.setdefault('reader',profile.get('reader',''))
    fw.setdefault('reader_formats',list(formats(printer_id,firmware_id)))
    fw.setdefault('effect','standalone' if formats(printer_id,firmware_id) else 'none')
    fw.setdefault('evidence','unverified')
    return fw


def categories(printer_id: str) -> set[str]:
    """A printer may have both a proprietary original reader and an added one."""
    result=set()
    for fw in PROFILES[printer_id]['firmwares']:
        c=configuration(printer_id,fw['id'])
        if formats(printer_id,fw['id']):
            result.update(('compatible',c['connection'],c['firmware_kind']))
        elif c['reader_formats']:
            result.add('rfid')
    if 'compatible' not in result and 'rfid' not in result:result.add('none')
    return result


def can_export(printer_id: str, firmware_id: str | None = None, export_format=None) -> bool:
    supported=formats(printer_id,firmware_id)
    return export_format in supported if export_format is not None else bool(supported)


def describe(printer_id: str, firmware_id: str | None = None) -> str:
    printer_id, firmware_id = resolve(printer_id, firmware_id)
    fw = firmware(printer_id, firmware_id)
    label = PROFILES[printer_id]["label"]
    return f"{label} — {fw['label']}" if len(PROFILES[printer_id]["firmwares"]) > 1 else label


def install_catalogue(raw: bytes) -> dict:
    """Validate a downloaded list and install it only if it supersedes the active reliable list.

    The candidate is compared with the active list (bundled or user copy) by time
    value. Equal date: identical data is ``unchanged`` (nothing written), different
    data is a conflict. Profiles are prepared in memory before anything is written;
    the user file is published atomically under lock with revision control
    (``scripts.db_io``). Any refusal or failure keeps the active list and PROFILES.
    The returned document carries ``_update`` = ``installed`` or ``unchanged``.
    """
    candidate = parse_catalogue_bytes(raw)
    refusal = update_refusal(candidate)
    if refusal:
        _fail(refusal, 'Liste sans date ou source vérifiable : non installée.')
    target = user_path()
    if target is None:
        raise ValueError("Dossier de données inconnu.")
    from scripts import db_io
    try:
        digest = hashlib.sha256()
        with open(target, 'rb') as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b''):
                digest.update(chunk)
        revision = digest.hexdigest()
    except FileNotFoundError:
        revision = None
    active = load_catalogue()
    decision = compare_update(active, candidate)
    if decision == 'unchanged':
        return dict(active, _update='unchanged')
    if decision != 'install':
        _fail(decision, {'regression': 'Liste plus ancienne que la liste active : conservée.',
                         'conflict': 'Même date, contenu différent : liste active conservée.'}.get(decision, decision))
    installed = dict(candidate, _origin='user')
    prepared = _profiles(installed)
    try:
        db_io.save_validated_json(target, candidate, revision, validate_catalogue, max_bytes=MAX_CATALOGUE_BYTES)
    except (db_io.DatabaseError, OSError) as exc:
        raise CatalogueError('storage', str(exc)) from exc
    PROFILES.clear()
    PROFILES.update(prepared)
    return dict(installed, _update='installed')


def refresh_catalogue(fetch) -> dict | None:
    """A development list may not exist on main yet; keep the bundled one.

    Other HTTP/network errors remain errors, and no invalid response is installed.
    """
    try:
        raw = fetch(PRINTERS_URL, 512 * 1024)
    except HTTPError as exc:
        if exc.code == 404:
            return None
        raise
    return install_catalogue(raw)
